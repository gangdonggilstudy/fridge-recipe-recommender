def infer_taste(ingredients: list[str]) -> list[str]:
    """재료 목록에서 맛 태그 자동 추론. 미해당 시 ['담백함'] 반환.

    시스템 레시피(build_recipes)와 커스텀 레시피(custom_recipe_repo) 공통 출처.
    재료는 normalize_ingredient() 정규화 후 전달해야 정확도가 유지된다.
    """
    result = [
        taste
        for taste, markers in TASTE_MARKERS.items()
        if any(ing in markers for ing in ingredients)
    ]
    return result or ["담백함"]


def normalize_ingredient(name: str) -> str:
    """재료명 표준 표기로 변환. 공백 제거 후 별칭 매핑 적용."""
    name = name.strip().replace(" ", "")
    return INGREDIENT_ALIASES.get(name, name)


def validate_enum(category: str, value: str) -> str:
    """enum 값 검증. 미일치 시 ValueError 발생."""
    if category not in ALLOWED_ENUMS:
        raise ValueError(f"Unknown enum category: {category}")
    value = value.strip()
    if value not in ALLOWED_ENUMS[category]:
        raise ValueError(
            f"Invalid {category}: '{value}'. Allowed: {sorted(ALLOWED_ENUMS[category])}"
        )
    return value


def split_multi(value: str) -> list[str]:
    """쉼표 구분 복수 값을 리스트로 분해. 공백·빈 값 제거."""
    if not value:
        return []
    return [v.strip() for v in value.split(",") if v.strip()]
